# ANSI order (as the console uses it): black red green yellow blue magenta cyan white,
# then the bright versions.
CGA = "000000 aa0000 00aa00 aa5500 0000aa aa00aa 00aaaa aaaaaa 555555 ff5555 55ff55 ffff55 5555ff ff55ff 55ffff ffffff"


def mono(dark, mid, bright):
    """A monochrome CRT palette: everything becomes a shade of one phosphor."""
    shades = {"k": "000000", "d": dark, "m": mid, "b": bright}
    #          blk red grn yel blu mag cyn wht | gry red grn yel blu mag cyn wht
    layout = "k   d   m   m   d   d   m   m     d   m   b   b   m   m   b   b".split()
    return " ".join(shades[x] for x in layout)


