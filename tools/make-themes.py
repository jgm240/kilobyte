"""Generate Kilobyte's colour themes into rootfs/usr/share/kilobyte/themes.

Each theme is a dialogrc (the colours of every dialog(1) element), an mc skin
name and optionally a 16-colour Linux console palette. Colours are limited to
what a DOS text screen had: 8 background colours, 16 foreground colours (a
"bright" foreground is the ON flag).

Run it after editing this file:  python3 tools/make-themes.py
"""
