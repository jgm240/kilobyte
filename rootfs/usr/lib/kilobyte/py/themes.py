#!/usr/bin/python3
"""Kilobyte's colour themes: the roles of a theme, turned into dialog's
colour file, and your own themes (Settings > Colour theme > Theme editor).

A theme is a short text file of roles, one per line:

    name=My Theme
    mc=default                     the file manager's look (an mc skin)
    shadow=ON                      shadows under the windows
    palette=000000 aa0000 ...      16 exact colours (Linux console only)
    screen=CYAN,BLUE,ON            a role: text colour, background, bright
    ...

Your themes are kept in ~/.config/kilobyte/themes/my-NAME/, as theme.conf
and the files Kilobyte reads (dialogrc, name, mc-skin, palette). The same
theme.conf, saved anywhere as NAME.kbtheme, shares a theme.

    themes.py new BASE-DIR DIR NAME     a theme of your own, copied from BASE
    themes.py get DIR                   its roles, KEY=VALUE
    themes.py set DIR KEY VALUE         change one, and make the files anew
    themes.py export DIR FILE           save it to share
    themes.py import FILE THEMES-DIR    a shared one: prints its new folder name
    themes.py sample                    the colour names, for the menus
    themes.py code DIR                  a theme as a short code (for the gallery)
    themes.py fromcode CODE THEMES-DIR  a theme from a code: prints its folder name
    themes.py decode CODE               a code's theme, as JSON (the gallery's checks)

The code (version 1), in URL-safe base64 without padding: a version byte (1);
flags (1: shadows, 2: exact colours follow); the file manager look (its
place in MC_SKINS); one byte for each role in ROLES' order, text colour
(0-15) * 8 + background (0-7); if flag 2, 16 colours of 3 bytes; then the
name in UTF-8 (up to 40 bytes).
"""
import base64
import os
import re
import sys

# The roles, in the order the editor lists them, with their names there.
ROLES = [
    ("screen", "Desk (behind the windows)"),
    ("dialog", "Window text"),
    ("title", "Window titles"),
    ("border", "Window frame, light side"),
    ("border2", "Window frame, dark side"),
    ("item", "Menu items"),
    ("sel", "Chosen menu item"),
    ("tag", "Menu names"),
    ("sel_tag", "Chosen menu name"),
    ("key", "First letters"),
    ("sel_key", "First letter, chosen item"),
    ("btn_on", "Chosen button"),
    ("btn_off", "Other buttons"),
    ("btn_key_on", "Letter on the chosen button"),
    ("btn_key_off", "Letter on other buttons"),
    ("input", "Typing fields"),
    ("arrow", "Scroll arrows"),
    ("status", "Help line"),
    ("gauge", "Progress bars"),
]
ROLE_KEYS = [k for k, _ in ROLES]

# The 16 colours as dialog names them: 8 colours, and bright ones (ON).
BASE = ["BLACK", "RED", "GREEN", "YELLOW", "BLUE", "MAGENTA", "CYAN", "WHITE"]
NAMES = ["black", "red", "green", "brown", "blue", "magenta", "cyan", "lightgrey",
         "darkgrey", "lightred", "lightgreen", "yellow", "lightblue", "lightmagenta", "lightcyan", "white"]
# (Those that look right on the console's 16 colours.)
MC_SKINS = ["default", "dark", "darkfar", "double-lines", "gotar", "mc46", "nicedark"]

# dialogrc lines, from the roles (several share one role).
DIALOGRC = {
    "screen_color": "screen", "shadow_color": None, "dialog_color": "dialog", "title_color": "title",
    "border_color": "border", "border2_color": "border2",
    "button_active_color": "btn_on", "button_inactive_color": "btn_off",
    "button_key_active_color": "btn_key_on", "button_key_inactive_color": "btn_key_off",
    "button_label_active_color": "btn_on", "button_label_inactive_color": "btn_off",
    "inputbox_color": "input", "inputbox_border_color": "border", "inputbox_border2_color": "border2",
    "searchbox_color": "dialog", "searchbox_title_color": "title", "searchbox_border_color": "border",
    "searchbox_border2_color": "border2", "position_indicator_color": "title",
    "menubox_color": "dialog", "menubox_border_color": "border2", "menubox_border2_color": "border",
    "item_color": "item", "item_selected_color": "sel", "tag_color": "tag", "tag_selected_color": "sel_tag",
    "tag_key_color": "key", "tag_key_selected_color": "sel_key", "check_color": "item",
    "check_selected_color": "sel", "uarrow_color": "arrow", "darrow_color": "arrow",
    "itemhelp_color": "status", "form_active_text_color": "input", "form_text_color": "dialog",
    "form_item_readonly_color": "tag", "gauge_color": "gauge",
}

COLOUR = re.compile(r"^\(?(BLACK|RED|GREEN|YELLOW|BLUE|MAGENTA|CYAN|WHITE),(BLACK|RED|GREEN|YELLOW|BLUE|MAGENTA|CYAN|WHITE),(ON|OFF)\)?$")
PALETTE = re.compile(r"^([0-9a-fA-F]{6} ){15}[0-9a-fA-F]{6}$")


def rc(t, generator="tools/make-themes.py"):
    """A theme's roles as a complete dialogrc."""
    lines = [
        f"# Kilobyte theme: generated by {generator}, do not edit",
        "aspect = 0",
        "separate_widget = \"\"",
        "tab_len = 0",
        "visit_items = OFF",
        f"use_shadow = {t.get('shadow_on', 'ON')}",
        f"use_colors = {t.get('colors_on', 'ON')}",
    ]
    for key, role in DIALOGRC.items():
        value = t.get(role, "(BLACK,BLACK,OFF)") if role else t.get("shadow", "(BLACK,BLACK,OFF)")
        lines.append(f"{key} = {value}")
    return "\n".join(lines) + "\n"


def read_conf(path):
    """theme.conf (or a .kbtheme) as a dict; anything unknown or malformed is
    left out, so a shared theme can only ever be colours."""
    t = {}
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = (s.strip() for s in line.split("=", 1))
            if k == "name":
                v = re.sub(r"[^\w .,'()&+-]", "", v)[:40].strip()
                if v:
                    t["name"] = v
            elif k == "mc" and v in MC_SKINS:
                t["mc"] = v
            elif k == "shadow" and v in ("ON", "OFF"):
                t["shadow"] = v
            elif k == "palette" and PALETTE.match(v):
                t["palette"] = v.lower()
            elif k in ROLE_KEYS and COLOUR.match(v):
                t[k] = v.strip("()")
    return t


def from_dir(d):
    """The roles of an installed theme, read back from its dialogrc."""
    t = {"name": "Theme", "mc": "default", "shadow": "ON"}
    back = {}
    for key, role in DIALOGRC.items():
        if role and role not in back.values():
            back[key] = role
    try:
        with open(os.path.join(d, "dialogrc")) as f:
            for line in f:
                m = re.match(r"\s*(\w+)\s*=\s*(.+?)\s*$", line)
                if not m:
                    continue
                key, value = m.groups()
                if key == "use_shadow" and value in ("ON", "OFF"):
                    t["shadow"] = value
                elif key in back and COLOUR.match(value):
                    t[back[key]] = value.strip("()")
    except OSError:
        pass
    for name, f in (("name", "name"), ("mc", "mc-skin")):
        try:
            with open(os.path.join(d, f)) as fh:
                t[name] = fh.read().strip() or t[name]
        except OSError:
            pass
    try:
        with open(os.path.join(d, "palette")) as f:
            p = " ".join(line.strip() for line in f if line.strip())
            if PALETTE.match(p):
                t["palette"] = p
    except OSError:
        pass
    for k in ROLE_KEYS:
        t.setdefault(k, "BLACK,WHITE,OFF")
    return t


def write(d, t):
    """theme.conf and the files Kilobyte reads, in folder d."""
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "theme.conf"), "w") as f:
        f.write(conf_text(t))
    roles = {k: "(" + t[k] + ")" for k in ROLE_KEYS if k in t}
    roles["shadow_on"] = t.get("shadow", "ON")
    with open(os.path.join(d, "dialogrc"), "w") as f:
        f.write(rc(roles, "Kilobyte's theme editor"))
    with open(os.path.join(d, "name"), "w") as f:
        f.write(t.get("name", "My theme") + "\n")
    with open(os.path.join(d, "mc-skin"), "w") as f:
        f.write(t.get("mc", "default") + "\n")
    path = os.path.join(d, "palette")
    if "palette" in t:
        with open(path, "w") as f:
            f.write("\n".join(t["palette"].split()) + "\n")
    elif os.path.exists(path):
        os.remove(path)


def conf_text(t):
    out = ["# Kilobyte theme (Settings > Colour theme > Theme editor)",
           f"name={t.get('name', 'My theme')}", f"mc={t.get('mc', 'default')}",
           f"shadow={t.get('shadow', 'ON')}"]
    if "palette" in t:
        out.append(f"palette={t['palette']}")
    out += [f"{k}={t[k]}" for k in ROLE_KEYS if k in t]
    return "\n".join(out) + "\n"


def folder_name(name, root):
    """A new folder for a theme called name: my-NAME, my-NAME-2 ..."""
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    base = "my-" + (re.sub(r"^my-", "", slug)[:24] or "theme")
    d, n = base, 2
    while os.path.exists(os.path.join(root, d)):
        d, n = f"{base}-{n}", n + 1
    return d


def to_code(t):
    """A theme (as read_conf gives it) as a short code."""
    flags = (1 if t.get("shadow", "ON") == "ON" else 0) | (2 if "palette" in t else 0)
    mc = MC_SKINS.index(t.get("mc", "default")) if t.get("mc", "default") in MC_SKINS else 0
    data = bytearray([1, flags, mc])
    for k in ROLE_KEYS:
        fg, bg, on = t[k].split(",")
        data.append((BASE.index(fg) + (8 if on == "ON" else 0)) * 8 + BASE.index(bg))
    if flags & 2:
        data += bytes.fromhex("".join(t["palette"].split()))
    data += t.get("name", "Theme").encode("utf-8")[:40]
    return base64.urlsafe_b64encode(bytes(data)).decode().rstrip("=")


def from_code(code):
    """A code as a theme; ValueError if it is not one."""
    if not re.fullmatch(r"[A-Za-z0-9_-]{20,200}", code or ""):
        raise ValueError("not a theme code")
    data = base64.urlsafe_b64decode(code + "=" * (-len(code) % 4))
    if len(data) < 3 + len(ROLE_KEYS) or data[0] != 1:
        raise ValueError("not a theme code (or one from a newer Kilobyte)")
    flags, mc = data[1], data[2]
    if mc >= len(MC_SKINS):
        raise ValueError("not a theme code")
    t = {"shadow": "ON" if flags & 1 else "OFF", "mc": MC_SKINS[mc]}
    i = 3
    for k in ROLE_KEYS:
        v = data[i]
        fg, bg = v // 8, v % 8
        if fg > 15:
            raise ValueError("not a theme code")
        t[k] = "%s,%s,%s" % (BASE[fg & 7], BASE[bg], "ON" if fg >= 8 else "OFF")
        i += 1
    if flags & 2:
        if len(data) < i + 48:
            raise ValueError("not a theme code")
        t["palette"] = " ".join(data[i + 3 * j:i + 3 * j + 3].hex() for j in range(16))
        i += 48
    name = re.sub(r"[^\w .,'()&+-]", "", data[i:].decode("utf-8", "replace"))[:40].strip()
    t["name"] = name or "Gallery theme"
    return t


def main(args):
    cmd = args[0] if args else ""
    if cmd == "new" and len(args) == 4:
        t = from_dir(args[1])
        t["name"] = re.sub(r"[^\w .,'()&+-]", "", args[3])[:40].strip() or "My theme"
        write(args[2], t)
    elif cmd == "get" and len(args) == 2:
        t = read_conf(os.path.join(args[1], "theme.conf"))
        for k in ["name", "mc", "shadow", "palette"] + ROLE_KEYS:
            if k in t:
                print(f"{k}={t[k]}")
    elif cmd == "set" and len(args) == 4:
        t = read_conf(os.path.join(args[1], "theme.conf"))
        t[args[2]] = args[3]
        if args[2] == "palette" and args[3] == "":
            t.pop("palette")
        # (Through the same checks as a shared theme.)
        tmp = os.path.join(args[1], "theme.conf.new")
        with open(tmp, "w") as f:
            f.write(conf_text(t))
        checked = read_conf(tmp)
        os.remove(tmp)
        if args[2] != "palette" and args[2] not in checked:
            sys.exit(f"not a usable value for {args[2]}: {args[3]}")
        write(args[1], checked)
    elif cmd == "export" and len(args) == 3:
        t = read_conf(os.path.join(args[1], "theme.conf"))
        with open(args[2], "w") as f:
            f.write(conf_text(t))
    elif cmd == "import" and len(args) == 3:
        t = read_conf(args[1])
        missing = [k for k in ROLE_KEYS if k not in t]
        if len(missing) == len(ROLE_KEYS):
            sys.exit("This is not a Kilobyte theme.")
        base = from_dir("/usr/share/kilobyte/themes/classic")
        for k in missing:                           # an older or partial theme
            t[k] = base[k]
        t.setdefault("name", os.path.splitext(os.path.basename(args[1]))[0][:40])
        d = folder_name(t["name"], args[2])
        write(os.path.join(args[2], d), t)
        print(d)
    elif cmd == "code" and len(args) == 2:
        t = read_conf(os.path.join(args[1], "theme.conf")) if os.path.exists(os.path.join(args[1], "theme.conf")) else from_dir(args[1])
        print(to_code(t))
    elif cmd == "fromcode" and len(args) == 3:
        try:
            t = from_code(args[1])
        except (ValueError, UnicodeDecodeError) as e:
            sys.exit(str(e))
        d = folder_name(t["name"], args[2])
        write(os.path.join(args[2], d), t)
        print(d)
    elif cmd == "decode" and len(args) == 2:
        import json
        try:
            print(json.dumps(from_code(args[1]), ensure_ascii=False))
        except (ValueError, UnicodeDecodeError) as e:
            sys.exit(str(e))
    elif cmd == "folder" and len(args) == 3:
        print(folder_name(args[1], args[2]))
    elif cmd == "roles":
        for k, label in ROLES:
            print(f"{k}|{label}")
    elif cmd == "sample":
        for i, n in enumerate(NAMES):
            print(f"{n}|{BASE[i & 7]},{'ON' if i >= 8 else 'OFF'}")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
